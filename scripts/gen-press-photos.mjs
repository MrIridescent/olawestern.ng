/**
 * gen-press-photos.mjs — turns data/press-media.json into src/lib/pressPhotos.ts
 * (run automatically by harvest-press-media.mjs, or by hand after a re-harvest).
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(new URL('..', import.meta.url).pathname.replace(/^\/(\w:)/, '$1'));
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'press-media.json'), 'utf8'));

const q = (s) => String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");

const rows = manifest.map((x) => {
  const base = x.file.split('/').pop().replace(/\.(jpg|jpeg|png|webp|avif|gif)$/i, '');
  const id = `ph-${base}`.slice(0, 60);
  const outlet = q(x.credit.replace(/^Photo:\s*/, ''));
  return `  { id: '${id}', src: '${q(x.file)}', width: ${x.width}, height: ${x.height}, orientation: '${x.orientation}', year: ${x.year}, outlet: '${outlet}', headline: '${q(x.caption)}', url: '${q(x.source_url)}' },`;
});

const out = `/**
 * pressPhotos.ts — GENERATED by scripts/gen-press-photos.mjs from
 * data/press-media.json (see scripts/harvest-press-media.mjs).
 *
 * Real photographs published by the outlets that covered Ola Western, taken
 * from each article's og:image with its true pixel dimensions and source URL.
 * These are press images: every row keeps its outlet credit and the article it
 * came from, and the campaign CMS can replace or unpublish any of them.
 * Editorial choices (which slot a photo fills, its caption) live in
 * src/lib/content.ts — this file is data, not copy.
 */
export interface PressPhoto {
  id: string;
  src: string;
  width: number;
  height: number;
  orientation: 'portrait' | 'landscape' | 'square';
  year: number;
  outlet: string;
  headline: string;
  url: string;
}

export const PRESS_PHOTOS: PressPhoto[] = [
${rows.join('\n')}
];
`;

fs.writeFileSync(path.join(ROOT, 'src', 'lib', 'pressPhotos.ts'), out);
console.log(`${rows.length} press photos → src/lib/pressPhotos.ts`);
