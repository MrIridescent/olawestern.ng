/**
 * sharpen-press-archive.mjs — rebuild the photographic record at web weight.
 *
 * The press desk keeps the outlet's original on disk. Display frames are small,
 * so this pass resizes each photo to a sensible long edge, applies a restrained
 * unsharp mask (the originals are mostly phone uploads), and writes a modern
 * progressive JPEG into public/images/archive/. It never crops, never invents
 * detail and never changes the aspect ratio — only the pixel size and edge
 * contrast. The generated TypeScript file is the data the site renders.
 *
 * Usage: node scripts/sharpen-press-archive.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = process.cwd();
const INPUT = path.join(ROOT, 'scripts', 'press-archive-curated.json');
const OUT_DIR = path.join(ROOT, 'public', 'images', 'archive');
const TS_OUT = path.join(ROOT, 'src', 'lib', 'pressArchive.ts');

const clamp = (n, lo, hi) => Math.min(hi, Math.max(lo, n));

const rows = JSON.parse(fs.readFileSync(INPUT, 'utf8'));
fs.mkdirSync(OUT_DIR, { recursive: true });

const done = [];

for (const row of rows) {
  const src = path.join(ROOT, row.source);
  if (!fs.existsSync(src)) throw new Error(`missing source: ${row.source}`);
  const meta = await sharp(src).metadata();
  if (!meta.width || !meta.height) throw new Error(`unreadable: ${row.source}`);

  const long = Math.max(meta.width, meta.height);
  const targetLong = Math.round(clamp(long * 1.6, 1200, 2400));
  const scale = targetLong / long;

  const width = Math.round(meta.width * scale);
  const height = Math.round(meta.height * scale);
  const outFile = path.join(ROOT, 'public', row.out.replace(/^\//, ''));
  fs.mkdirSync(path.dirname(outFile), { recursive: true });

  const pipeline = sharp(src)
    .rotate()
    .resize(width, height, { fit: 'fill', kernel: 'lanczos3' })
    .sharpen({ sigma: 0.9, m1: 1.0, m2: 0.45 })
    .modulate({ brightness: 1.01, saturation: 1.02 });

  await pipeline
    .jpeg({ quality: 86, mozjpeg: true, progressive: true, chromaSubsampling: '4:4:4' })
    .toFile(outFile);

  const orientation =
    width === height ? 'square' : width > height ? 'landscape' : 'portrait';

  done.push({ ...row, width, height, orientation });
  console.log(
    `✓ ${row.id.padEnd(34)} ${meta.width}×${meta.height} → ${width}×${height} (${orientation})`,
  );
}

const ts = `/**
 * pressArchive.ts — GENERATED by scripts/sharpen-press-archive.mjs.
 *
 * The campaign's photographic record: every frame carries the outlet that
 * published it, the date, the report it ran in and a link to that report.
 * Captions say only what the source says; alt text describes the frame.
 * Edit scripts/press-archive-curated.json and re-run the script — do not hand
 * edit this file.
 */
export interface ArchivePhoto {
  id: string;
  src: string;
  width: number;
  height: number;
  orientation: 'portrait' | 'landscape' | 'square';
  year: number;
  date: string;
  outlet: string;
  headline: string;
  alt: string;
  caption: string;
  credit: string;
  source_url: string;
  image_url: string;
  featured: boolean;
}

export const PRESS_ARCHIVE: ArchivePhoto[] = ${JSON.stringify(
  done.map((r) => ({
    id: r.id,
    src: r.out,
    width: r.width,
    height: r.height,
    orientation: r.orientation,
    year: r.year,
    date: r.date,
    outlet: r.outlet,
    headline: r.headline,
    alt: r.alt,
    caption: r.caption,
    credit: r.credit,
    source_url: r.source_url,
    image_url: r.image_url,
    featured: r.featured,
  })),
  null,
  2,
)};

export const ARCHIVE_YEARS: number[] = Array.from(
  new Set(PRESS_ARCHIVE.map((p) => p.year)),
).sort((a, b) => b - a);

export const FEATURED_ARCHIVE: ArchivePhoto[] = PRESS_ARCHIVE.filter((p) => p.featured);
`;

fs.writeFileSync(TS_OUT, ts);
console.log(`\n${done.length} photos → public/images/archive/`);
console.log(`data → ${path.relative(ROOT, TS_OUT)}`);
